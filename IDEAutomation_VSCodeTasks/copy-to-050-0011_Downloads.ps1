$sourceDir  = $PSScriptRoot | Split-Path -Parent
$sourceFile = "ClientSMBFixEnableNetworkDiscoveryFileSharing.ps1"
$sourcePath = Join-Path $sourceDir $sourceFile
$dest       = "\\050-0011\Users\user50\Downloads"
$logFile    = Join-Path $PSScriptRoot "copy-to-050-0011_Downloads_Githook.log"

function Get-FileSha256 {
    param([string]$Path)

    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($sha256.ComputeHash([System.IO.File]::ReadAllBytes($Path)))).Replace('-', '')
    } finally {
        $sha256.Dispose()
    }
}

function Get-RobocopyStatus {
    param([int]$Code)

    switch ($Code) {
        0  { return "No files copied. SHA-256 source and destination content matched." }
        1  { return "Files copied successfully." }
        2  { return "Extra files or directories were detected; no files copied." }
        3  { return "Files copied successfully." }
        5  { return "Some files were copied, but some files were mismatched." }
        6  { return "Additional files and mismatched files were present." }
        7  { return "Files copied; additional files and mismatched files were present." }
        8  { return "Robocopy failed. At least one file could not be copied." }
        default { return "Unknown robocopy exit code: $Code" }
    }
}

if (-not (Test-Path $sourcePath)) {
    Write-Error "[post-commit] Source file not found: $sourcePath"
    exit 1
}

if (-not (Test-Path $dest)) {
    Write-Error "[post-commit] Destination UNC is unavailable or not reachable: $dest"
    Write-Error "[post-commit] Aborting because the network share is not accessible."
    exit 1
}

# clear prior log file
if (Test-Path $logFile) {
    Remove-Item $logFile -Force
}

@(
    "Generated by PowerShell script: $PSCommandPath"
    "Generated at: $(Get-Date -Format 'yyyy-MM-dd-HHmmss')"
    "Source file: $sourcePath"
    "Destination: $dest"
    ""
) | Set-Content -Path $logFile -Encoding UTF8

$destFile = Join-Path $dest $sourceFile
$sourceHash = Get-FileSha256 -Path $sourcePath
$destinationHash = if (Test-Path $destFile) {
    Get-FileSha256 -Path $destFile
}

$contentMatches = $destinationHash -and ($sourceHash -eq $destinationHash)
if ($contentMatches) {
    Write-Host "[post-commit] SHA-256 content check: matched ($sourceHash)"
} else {
    Write-Host "[post-commit] SHA-256 content check: differs or destination is missing."
}

Write-Host "[post-commit] Source file: $sourcePath"
Write-Host "[post-commit] Destination: $dest"
Write-Host "[post-commit] Log file: $logFile"
Write-Host "[post-commit] Starting robocopy with verbose output (/V), ETA, and summary logging..."

& "C:\Windows\System32\robocopy.exe" `
    $sourceDir `
    $dest `
    $sourceFile `
    /V `
    /ETA `
    /R:1 `
    /W:1 `
    $(if ($destinationHash -and -not $contentMatches) { '/IS' }) `
    /TEE `
    /LOG+:$logFile

$rc = $LASTEXITCODE

Write-Host ""
Write-Host "[post-commit] robocopy exit code: $rc"
Write-Host "[post-commit] robocopy status: $(Get-RobocopyStatus -Code $rc)"
Write-Host "[post-commit] complete robocopy log output:"

if (Test-Path $logFile) {
    Get-Content $logFile | ForEach-Object {
        Write-Host $_
    }
}

if ($rc -eq 0 -or $rc -eq 1 -or $rc -eq 3) {
    if (Test-Path $destFile) {
        $destinationHash = Get-FileSha256 -Path $destFile
        if ($sourceHash -eq $destinationHash) {
            Write-Host "[SUCCESS] File verified successfully at: $destFile"
            exit 0
        }
        Write-Error "[FAILURE] Destination file hash does not match the source."
        Write-Error "[FAILURE] Source:      $sourceHash"
        Write-Error "[FAILURE] Destination: $destinationHash"
        exit 1
    }
    Write-Warning "[WARNING] robocopy reported success, but the destination file could not be verified: $destFile"
    exit 0
}

if ($rc -eq 8) {
    Write-Error "[FAILURE] robocopy reported a real copy problem."
    Write-Error "[FAILURE] Check share access, permissions, and the network path."
    exit 1
}

Write-Warning "[WARNING] robocopy returned status $rc; this is not a clean success, but it is not a hard failure either."
exit 0
