#Requires -Version 5.1

$sourceDir  = Split-Path -Parent $PSScriptRoot
$sourceFile = "ClientSMBFixEnableNetworkDiscoveryFileSharing.ps1"
$sourcePath = Join-Path $sourceDir $sourceFile
$logFile    = Join-Path $PSScriptRoot "copy-to-050-0011_via-psremoting-ssh_Githook.log"

function Get-FileSha256 {
    param([string]$Path)

    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($sha256.ComputeHash([System.IO.File]::ReadAllBytes($Path)))).Replace('-', '')
    } finally {
        $sha256.Dispose()
    }
}

if (-not (Test-Path $sourcePath)) {
    Write-Error "[post-commit] Source file not found: $sourcePath"
    exit 1
}

# Clear prior log file
if (Test-Path $logFile) {
    Remove-Item $logFile -Force
}

@(
    "Generated by PowerShell script: $PSCommandPath"
    "Generated at: $(Get-Date -Format 'yyyy-MM-dd-HHmmss')"
    "Source file: $sourcePath"
    "Target: 050-0011:2222 via PowerShell Remoting over SSH"
    "User: user50"
    "Target destination (expanded): $env:USERPROFILE\Downloads on remote (user50 profile)"
    ""
) | Set-Content -Path $logFile -Encoding UTF8

$localHash = Get-FileSha256 -Path $sourcePath
Write-Host "[post-commit] Source file: $sourcePath"
Write-Host "[post-commit] Source SHA-256: $localHash"
Write-Host "[post-commit] Target: 050-0011:2222 (PowerShell remoting over SSH)"
Write-Host "[post-commit] Using key: $env:USERPROFILE\.ssh\id_ed25519"

$sessionArgs = @{
    HostName     = "050-0011"
    Port         = 2222
    UserName     = "user50"
    KeyFilePath  = "$env:USERPROFILE\.ssh\id_ed25519"
    SSHTransport = $true
}

$session = $null
try {
    Write-Host "[post-commit] Establishing SSH PowerShell session..."
    $session = New-PSSession @sessionArgs -ErrorAction Stop
    Write-Host "[post-commit] Secure session established."

    Write-Host "[post-commit] Copying file to remote user's Downloads folder via Copy-Item -ToSession..."
    Invoke-Command -Session $session -ScriptBlock {
        $destDir = "$env:USERPROFILE\Downloads"
        if (-not (Test-Path $destDir)) {
            New-Item -ItemType Directory -Path $destDir -Force | Out-Null
        }
        $destDir
    } -OutVariable remoteDestDir | Out-Null

    $remoteDestDirPath = $remoteDestDir[0]
    Write-Host "[post-commit] Remote destination: $remoteDestDirPath"

    Copy-Item -Path $sourcePath -Destination $remoteDestDirPath -ToSession $session -Force -ErrorAction Stop
    Write-Host "[post-commit] File copied successfully."

    $remoteHash = Invoke-Command -Session $session -ScriptBlock {
        param($destFile)
        if (Test-Path $destFile) {
            $sha256 = [System.Security.Cryptography.SHA256]::Create()
            try {
                return ([BitConverter]::ToString($sha256.ComputeHash([System.IO.File]::ReadAllBytes($destFile)))).Replace('-', '')
            } finally {
                $sha256.Dispose()
            }
        }
        return $null
    } -ArgumentList (Join-Path $remoteDestDirPath $sourceFile)

    if ($remoteHash -eq $localHash) {
        Write-Host "[SUCCESS] File verified successfully on remote: $(Join-Path $remoteDestDirPath $sourceFile)"
        Write-Host "[SUCCESS] SHA-256 match: $localHash"
        @(
            ""
            "[SUCCESS] Copied: $sourceFile"
            "[SUCCESS] Remote: $(Join-Path $remoteDestDirPath $sourceFile)"
            "[SUCCESS] SHA-256: $localHash"
        ) | Add-Content -Path $logFile -Encoding UTF8
        exit 0
    } else {
        Write-Error "[FAILURE] Remote hash does not match local hash."
        Write-Error "[FAILURE] Local:  $localHash"
        Write-Error "[FAILURE] Remote: $remoteHash"
        @(
            ""
            "[FAILURE] Hash mismatch"
            "Local:  $localHash"
            "Remote: $remoteHash"
        ) | Add-Content -Path $logFile -Encoding UTF8
        exit 1
    }
}
catch {
    Write-Error "[FAILURE] $($_.Exception.Message)"
    @(
        ""
        "[FAILURE] $($_.Exception.Message)"
    ) | Add-Content -Path $logFile -Encoding UTF8
    exit 1
}
finally {
    if ($session) {
        Remove-PSSession $session
        Write-Host "[post-commit] Remote session closed."
    }
}
